class Furniture {
  final int id;
  final String name;
  final double price;
  final String brand;
  final double rating;
  final String image;
  final String furnitureType;
  final String dimensions;

  Furniture({
    required this.id,
    required this.name,
    required this.price,
    required this.brand,
    required this.rating,
    required this.image,
    required this.furnitureType,
    required this.dimensions,
  });
}
